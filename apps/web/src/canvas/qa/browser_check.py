"""Run against the running Person A preview: python browser_check.py.
Screenshots/report go to FOLLOW_QA_DIR (default /tmp/follow-canvas-qa).
Install this folder's requirements; run `python -m playwright install chromium`.
"""
from pathlib import Path
import json, os
from playwright.sync_api import sync_playwright, expect

ROOT = Path(__file__).resolve().parents[3]
OUT = Path(os.environ.get('FOLLOW_QA_DIR', '/tmp/follow-canvas-qa'))
OUT.mkdir(parents=True, exist_ok=True)
BASE = os.environ.get('FOLLOW_URL', 'http://127.0.0.1:5173')
checks = []
def check(condition, label):
    assert condition, label
    checks.append(label)
def settle(page):
    page.wait_for_timeout(450)
def capture(page, name):
    settle(page); page.screenshot(path=str(OUT / f'{name}.png'), full_page=True)
def audit(page, label):
    page.add_script_tag(path=str(ROOT / 'node_modules/axe-core/axe.min.js'))
    result = page.evaluate("async () => await axe.run(document, {runOnly: {type: 'tag', values: ['wcag2a','wcag2aa','wcag21aa']}})")
    violations = [{ 'id': v['id'], 'impact': v['impact'], 'nodes': [n['target'] for n in v['nodes']] } for v in result['violations']]
    check(not violations, f'{label}: axe WCAG A/AA {violations}')
def fit_check(page, label):
    result=page.locator('.react-flow__node:not([style*="display: none"]) .is-focused').evaluate_all("els => els.map(el => ({title: el.querySelector('h2').textContent, height: el.clientHeight, scroll: el.scrollHeight}))")
    check(all(x['scroll'] <= x['height']+2 for x in result),f'{label}: content fits fixed composition {result}')
    minimum=page.locator('.is-focused .node-summary,.is-focused .node-points li,.is-focused .step-label,.is-focused figcaption,.is-focused .metric-composition p').evaluate_all("els => { const zoom = new DOMMatrix(getComputedStyle(document.querySelector('.react-flow__viewport')).transform).a; const sizes=els.filter(el=>el.getBoundingClientRect().width && getComputedStyle(el).visibility !== 'hidden').map(el=>parseFloat(getComputedStyle(el).fontSize)*zoom); return sizes.length ? Math.min(...sizes) : 22; }")
    check(minimum >= 22,f'{label}: essential audience text remains at least 22 px ({minimum:.2f}px)')

with sync_playwright() as p:
    browser=p.chromium.launch(headless=True)
    page=browser.new_page(viewport={'width':1440,'height':900})
    errors=[]; page.on('pageerror',lambda e:errors.append(str(e)))
    page.goto(BASE);page.wait_for_load_state('networkidle')
    expect(page.get_by_role('heading',name='Big ideas. Room to follow.')).to_be_visible()
    audit(page,'Entry'); capture(page,'entry-desktop')
    page.locator('input[type=file]').first.set_input_files({'name':'bad.pdf','mimeType':'application/pdf','buffer':b'not a pdf'})
    expect(page.get_by_role('alert')).to_contain_text('PDF header');checks.append('Invalid PDF gives a recovery message')
    page.locator('input[type=file]').nth(1).set_input_files({'name':'bad.json','mimeType':'application/json','buffer':b'{broken'})
    expect(page.get_by_role('alert')).to_contain_text('not valid JSON');checks.append('Malformed JSON cannot enter the renderer')
    page.get_by_role('button',name='Open example canvas').click();settle(page)
    check(page.locator('.react-flow__node').count()==6,'Six example concepts render')
    audit(page,'Studio overview');capture(page,'studio-overview')
    page.get_by_role('button',name='Tools',exact=True).click()
    page.locator('.floating-lab').get_by_role('button',name='Action laboratory').click()
    expect(page.get_by_role('button',name='FOCUS',exact=True)).to_be_visible()
    page.get_by_role('button',name='HOLD',exact=True).click()
    expect(page.get_by_text('Hold · visual preserved')).to_be_visible();checks.append('HOLD retains the overview and reports hold')
    page.get_by_role('button',name='CONNECT',exact=True).click();settle(page)
    check(page.locator('.follow-canvas').get_attribute('data-view')=='connection','CONNECT composes approved endpoints')
    page.get_by_role('button',name='COMPARE',exact=True).click();settle(page)
    check(page.locator('.follow-canvas').get_attribute('data-view')=='comparison','COMPARE composes approved pair')
    page.get_by_role('button',name='OVERVIEW',exact=True).click()
    page.get_by_role('button',name='Tools',exact=True).click()
    page.get_by_role('button',name='From voice to visual.').click();settle(page)
    page.get_by_role('button',name='Compose the canvas',exact=True).click()
    page.get_by_role('button',name='Capture speech',exact=True).click()
    check(page.locator('.step-revealed').count()==2,'Process steps reveal out of order')
    page.get_by_role('button',name='Overview',exact=True).click()
    page.get_by_role('button',name='From voice to visual.').click();settle(page)
    check(page.locator('.step-revealed').count()==2,'Returning to a process preserves reveal state')
    page.get_by_role('button',name='Audience preview').click();settle(page)
    for width,height in [(1280,720),(1920,1080)]:
        page.set_viewport_size({'width':width,'height':height});settle(page)
        check(page.locator('aside,input,textarea,select').count()==0,f'Audience {width}: no private controls or inputs')
        fit_check(page,f'Process {width}');capture(page,f'audience-process-{height}')
    audit(page,'Audience process')
    page.get_by_role('button',name='Fullscreen',exact=True).click();settle(page)
    check(page.evaluate('!!document.fullscreenElement'),'Fullscreen begins from a user gesture')
    page.get_by_role('button',name='Exit fullscreen').focus();page.get_by_role('button',name='Exit fullscreen').press('Enter');settle(page)
    check(not page.evaluate('!!document.fullscreenElement'),'Fullscreen exit remains keyboard reachable')
    page.get_by_role('button',name='Back to studio').click()
    page.set_viewport_size({'width':1440,'height':900});settle(page)
    page.get_by_role('button',name='Flip who follows whom.').click()
    page.get_by_role('button',name='Audience preview').click()
    for width,height in [(1280,720),(1920,1080)]:
        page.set_viewport_size({'width':width,'height':height});settle(page)
        check(page.locator('.react-flow__node:visible').count()==2,f'Comparison {width}: unrelated nodes cannot bleed into frame')
        fit_check(page,f'Comparison {width}');capture(page,f'audience-comparison-{height}')
    page.get_by_role('button',name='Back to studio').click();page.set_viewport_size({'width':1440,'height':900});settle(page)
    for title,key in [('Meaning, beyond keywords.','metric'),('Prepared once. Followed locally.','figure'),('Your story. Not your slide order.','concept')]:
        page.get_by_role('button',name=title).click();settle(page)
        if key != 'figure':
            for button in page.locator('.reveal-controls button').all(): button.click()
        page.get_by_role('button',name='Audience preview').click();page.set_viewport_size({'width':1280,'height':720});settle(page)
        fit_check(page,key);audit(page,f'Audience {key}');capture(page,f'audience-{key}-720')
        page.get_by_role('button',name='Back to studio').click();page.set_viewport_size({'width':1440,'height':900});settle(page)
    page.get_by_role('button',name='Overview',exact=True).click()
    page.locator('.react-flow__node[data-id="pipeline"]').focus();page.keyboard.press('Enter');settle(page)
    check(page.locator('.follow-canvas').get_attribute('data-view')=='focus','Keyboard Enter focuses a canvas node')
    page.get_by_role('button',name='Text outline',exact=True).click();expect(page.locator('.outline-content')).to_be_visible();checks.append('Linear outline exposes all concepts and relationships')
    page.get_by_role('button',name='Close text outline').click()
