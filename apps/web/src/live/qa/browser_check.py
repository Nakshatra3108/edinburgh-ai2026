from pathlib import Path
import json, os, time
from playwright.sync_api import sync_playwright, expect
ROOT=Path(__file__).resolve().parents[5]
OUT=Path(os.environ.get('FOLLOW_QA_DIR','/tmp/follow-live-qa'));OUT.mkdir(parents=True,exist_ok=True)
checks=[]
def check(ok,label):
    assert ok,label
    checks.append(label)
def send(page,text):
    page.get_by_label('Type an explanation', exact=True).fill(text)
    page.get_by_role('button',name='Compose visual from explanation').click()
def audit(page,label):
    page.add_script_tag(path=str(ROOT/'node_modules/axe-core/axe.min.js'))
    violations=page.evaluate("async()=> (await axe.run(document,{runOnly:{type:'tag',values:['wcag2a','wcag2aa','wcag21aa']}})).violations.map(v=>({id:v.id,nodes:v.nodes.map(n=>n.target)}))")
    checks.append({'surface':label,'accessibilityViolations':violations})
with sync_playwright() as p:
    browser=p.chromium.launch(headless=True)
    page=browser.new_page(viewport={'width':1440,'height':900})
    errors=[];page.on('pageerror',lambda e:errors.append(str(e)))
    page.route('**/api/**', lambda route: route.fulfill(response=route.fetch(url='http://127.0.0.1:8790/api/'+route.request.url.split('/api/',1)[1])))
    page.goto(os.environ.get('FOLLOW_URL','http://127.0.0.1:5173'));page.wait_for_load_state('networkidle')
    page.get_by_label('Select source PDF').set_input_files(str(ROOT/'demo/source/follow-demo.pdf'))
    expect(page.get_by_role('heading',name='Knowledge first. Visuals as you speak.')).to_be_visible(timeout=20000)
    expect(page.get_by_role('button',name='Build knowledge base')).to_be_enabled()
    audit(page,'source desktop');page.screenshot(path=str(OUT/'source-desktop.png'),full_page=True)
    page.set_viewport_size({'width':1440,'height':900})
    page.get_by_role('button',name='Build knowledge base',exact=True).click()
    page.get_by_role('button',name='Open speaking studio').click(timeout=15000)
    expect(page.get_by_text('Your words build the canvas.')).to_be_visible()
    check(page.locator('.react-flow__node').count()==0,'presentation starts with empty canvas')
    audit(page,'studio empty');page.screenshot(path=str(OUT/'studio-empty.png'),full_page=True)
    send(page,'Explain the process used to turn speech into a canvas.')
    expect(page.locator('.live-status')).to_contain_text('Canvas updated',timeout=15000)
    expect(page.locator('.canvas-node.is-focused h2')).to_have_text('Four steps')
    expect(page.locator('.canvas-node.is-focused .step-label').first).to_be_visible()
    check(page.locator('.review-action').count()==0,'live process appears without manual review')
    page.screenshot(path=str(OUT/'process-desktop.png'),full_page=True)
    send(page,'Explain how the speaker directs the canvas.')
    expect(page.locator('.live-status')).to_contain_text('Canvas updated',timeout=15000)
    check(page.locator('.canvas-board .canvas-node.is-focused').count()==2,'new explanation retains earlier process beside it')
    page.wait_for_timeout(500)
    page.screenshot(path=str(OUT/'evolving-board-desktop.png'),full_page=True)
    send(page,'Please compare fixed slides with a speech-directed canvas.')
    expect(page.locator('.follow-canvas')).to_have_attribute('data-view','comparison',timeout=15000)
    check(page.locator('.canvas-node.is-focused').count()==2,'spoken comparison shows two composed ideas')
    audit(page,'studio comparison')
    page.wait_for_timeout(500)
    page.screenshot(path=str(OUT/'comparison-desktop.png'),full_page=True)
    send(page,'Explain the process used to turn speech into a canvas again.')
    expect(page.locator('.live-status')).to_contain_text('Canvas updated',timeout=15000)
    check(page.locator('.canvas-board .canvas-node.is-focused').count()==3,'process and recent contrasting ideas coexist on one board')
    page.wait_for_timeout(500)
    page.screenshot(path=str(OUT/'three-element-board-desktop.png'),full_page=True)
    send(page,'Please compare fixed slides with a speech-directed canvas.')
    expect(page.locator('.follow-canvas')).to_have_attribute('data-view','comparison',timeout=15000)
    page.set_viewport_size({'width':1280,'height':720});page.wait_for_timeout(500);page.screenshot(path=str(OUT/'comparison-720.png'),full_page=True)
    check(page.get_by_label('Type an explanation', exact=True).is_visible(),'typed controls visible at 720p')
    check(page.locator('.studio-canvas-wrap').bounding_box()['height']>=180,'canvas retains usable height at 720p')
    send(page,'This is an unrelated explanation of quantum elephants.')
    expect(page.locator('.live-status')).to_contain_text('No supporting material',timeout=15000)
    expect(page.locator('.follow-canvas')).to_have_attribute('data-view','comparison')
    checks.append('unrelated speech holds current visual')
    send(page,'A slow request explaining the speech-directed canvas. '+str(time.time_ns()))
    page.get_by_role('button',name='Hold canvas',exact=True).click()
    page.wait_for_timeout(1800)
    expect(page.locator('.follow-canvas')).to_have_attribute('data-view','comparison')
    expect(page.locator('.live-status')).to_contain_text('Paused')
    checks.append('manual hold suppresses delayed result')
    page.get_by_role('button',name='Audience preview').click()
    expect(page.locator('.audience-safe-area .follow-canvas')).to_have_attribute('data-view','comparison')
    page.wait_for_timeout(500);page.screenshot(path=str(OUT/'audience-720.png'),full_page=True)
    audit(page,'audience')
    page.get_by_role('button',name='Back to studio').click()
    check(all(not row['accessibilityViolations'] for row in checks if isinstance(row,dict)),'all desktop source, studio and audience accessibility checks pass')
    check(not errors,f'no browser runtime errors {errors}')
    (OUT/'report.json').write_text(json.dumps({'provider':'test fixture, no real Groq credentials','checks':checks},indent=2))
    print(json.dumps(checks,indent=2));browser.close()
